def _run(argv: list) -> int:
    if not argv or argv[0] in ("-h", "--help"):
        sys.stdout.write(HELP_TEXT)
        return 0 if argv else 1
    if not argv[0].startswith("-") and argv[0] != "init" and argv[0] not in COMMANDS:
        raise TeamError("unknown command: %s (run: team.py --help)" % argv[0])
    args = build_parser().parse_args(argv)
    if args.command == "init":
        return cmd_init(args)
    if args.command is None:
        sys.stdout.write(HELP_TEXT)
        return 1
    handler, agent_required = COMMANDS[args.command]
    agent = getattr(args, "agent", None) or os.environ.get("TEAM_AGENT") or None
    if agent_required and not agent:
        raise TeamError("%s needs --agent <ID> (or TEAM_AGENT); run join first if you have none"
                        % args.command)
    team_dir = resolve_team_dir()
    # Status is an observational snapshot: do not wait for or modify the writer lock, heartbeat
    # the caller, or regenerate the markdown views.
    if args.command == "status":
        return handler(team_dir, args, agent)
    if args.command in LOCK_FREE_COMMANDS:
        return handler(team_dir, args, agent)
    acquire_lock(team_dir, agent or "-")
    try:
        code = handler(team_dir, args, agent)
        if agent and args.command not in ("join", "inbox", "status"):
            print_unread_line(team_dir, agent)
        if args.command not in NO_RENDER_COMMANDS:
            render_views(team_dir)
    finally:
        release_lock(team_dir)
    return code


def main(argv: list | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    try:
        return _run(argv)
    except TeamError as err:
        if err.code == 2:
            line = "refused: %s. Run: team.py %s" % (err, err.hint)
        elif err.code == 3:
            line = "busy: %s; another agent is mid-change. Wait a moment and retry." % err
        else:
            line = "error: %s" % err
        print(line, file=sys.stderr)
        return err.code
    except SystemExit as exc:  # argparse --help
        return exc.code if isinstance(exc.code, int) else 0


if __name__ == "__main__":
    sys.exit(main())
