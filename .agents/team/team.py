def agent_path(team_dir: Path, agent_id: str) -> Path:
    return Path(team_dir) / "agents" / ("%s.json" % agent_id)


def task_path(team_dir: Path, task_id: str) -> Path:
    return Path(team_dir) / "tasks" / ("%s.json" % task_id)


def load_agents(team_dir: Path) -> list:
    folder = Path(team_dir) / "agents"
    return [read_json(p) for p in sorted(folder.glob("*.json"))]


def _task_number(task_id: str) -> int:
    return int(task_id[1:])


def load_tasks(team_dir: Path) -> list:
    folder = Path(team_dir) / "tasks"
    tasks = [read_json(p) for p in folder.glob("T*.json") if TASK_ID_RE.match(p.stem)]
    return sorted(tasks, key=lambda t: _task_number(t["id"]))


def load_task(team_dir: Path, task_id: str) -> dict | None:
    if not TASK_ID_RE.match(task_id or ""):
        return None
    path = task_path(team_dir, task_id)
    if not path.is_file():
        return None
    return read_json(path)


def save_task(team_dir: Path, task: dict) -> None:
    write_json_atomic(task_path(team_dir, task["id"]), task)


def append_jsonl(path: Path, obj) -> None:
    """Append one JSON line. If a crashed writer left a last line without its newline, end that
    line first, so the new entry is not glued onto it."""
    line = json.dumps(obj, ensure_ascii=False) + "\n"
    with contextlib.suppress(FileNotFoundError):
        with open(path, "rb") as handle:
            handle.seek(0, os.SEEK_END)
            if handle.tell() > 0:
                handle.seek(-1, os.SEEK_END)
                if handle.read(1) != b"\n":
                    line = "\n" + line
    with open(path, "a", encoding="utf-8", newline="\n") as handle:
        handle.write(line)
        handle.flush()
        os.fsync(handle.fileno())


def send_message(team_dir: Path, sender: str, to: str, kind: str, text: str,
                 task: str | None = None) -> int:
    """Append one message and return its ID: 1 + the lines already in messages.jsonl. The caller
    holds the team lock, which is what keeps IDs unique and strictly increasing."""
    path = Path(team_dir) / "messages.jsonl"
    count = 0
    if path.is_file():
        with open(path, "r", encoding="utf-8") as handle:
            count = sum(1 for _ in handle)
    message = {"id": count + 1, "at": now_iso(), "from": sender, "to": to, "kind": kind,
               "task": task, "text": text}
    append_jsonl(path, message)
    return message["id"]


def next_question_id(team_dir: Path) -> str:
    folder = Path(team_dir) / "questions"
    numbers = [int(p.stem[1:]) for p in folder.glob("Q*.json") if QUESTION_ID_RE.match(p.stem)]
    return "Q%03d" % (max(numbers, default=0) + 1)


def create_question(team_dir: Path, by: str, text: str, task: str | None = None) -> str:
    qid = next_question_id(team_dir)
    write_json_atomic(Path(team_dir) / "questions" / ("%s.json" % qid),
                      {"id": qid, "at": now_iso(), "by": by, "task": task, "text": text,
                       "status": "open", "resolution": None})
    return qid


def next_task_id(team_dir: Path) -> str:
    folder = Path(team_dir) / "tasks"
    numbers = [_task_number(p.stem) for p in folder.glob("T*.json") if TASK_ID_RE.match(p.stem)]
    return "T%03d" % (max(numbers, default=0) + 1)


def touch_agent(team_dir: Path, agent_id: str) -> dict:
    """Heartbeat: update last_seen and return the agent record. `user` is always accepted."""
    if agent_id == USER:
        return {"id": USER, "label": USER, "joined_at": None, "last_seen": None,
                "status": "active", "current_task": None, "inbox_cursor": 0}
    unknown = refuse("unknown agent; run join first (%s is not an active agent ID)" % agent_id,
                     'join --label "<your tool name>"')
    path = agent_path(team_dir, agent_id) if AGENT_ID_RE.match(agent_id or "") else None
    if path is None or not path.is_file():
        raise unknown
    agent = read_json(path)
    # On a case-insensitive disk A1.json opens a1.json; the stored id must match exactly.
    if agent.get("id") != agent_id or agent.get("status") != "active":
        raise unknown
    agent["last_seen"] = now_iso()
    write_json_atomic(path, agent)
    return agent


def save_agent(team_dir: Path, agent: dict) -> None:
    if agent["id"] != USER:
        write_json_atomic(agent_path(team_dir, agent["id"]), agent)


def is_stale(agent: dict, stale_minutes: float) -> bool:
    if agent.get("status") != "active" or not agent.get("last_seen"):
        return False
    busy_until = agent.get("busy_until")
    if busy_until and parse_iso(busy_until) > datetime.now(timezone.utc):
        return False
    age = datetime.now(timezone.utc) - parse_iso(agent["last_seen"])
    return age > timedelta(minutes=float(stale_minutes))


def coordinator_ids(team_dir: Path, config: dict) -> list:
    """Return active, non-stale coordinator IDs in stable order."""
    return sorted(agent["id"] for agent in load_agents(team_dir)
                  if agent.get("role") == "coordinator" and agent.get("status") == "active"
                  and not is_stale(agent, config["stale_minutes"]))


def attention_items(team_dir: Path, config: dict) -> list:
    """Return the current team events that need a person or coordinator to notice them."""
    items = []
    questions = sorted((read_json(path) for path in (Path(team_dir) / "questions").glob("Q*.json")),
                       key=lambda question: question.get("id", ""))
    for question in questions:
        if question.get("status") == "open":
            qid = question["id"]
            items.append({"key": "question:%s" % qid, "kind": "question",
                          "task": question.get("task"), "text": "Question %s is open." % qid})

    tasks = load_tasks(team_dir)
    agents = {agent["id"]: agent for agent in load_agents(team_dir)}
    questions_by_id = {question.get("id"): question for question in questions}
    for task in tasks:
        if task.get("status") == "review":
            tid = task["id"]
            items.append({"key": "review:%s" % tid, "kind": "review", "task": tid,
                          "text": "Task %s is awaiting review." % tid})

    for task in tasks:
        owner = task.get("owner")
        if task.get("status") not in LIVE_STATUSES or not owner or owner == USER:
            continue
        owner_record = agents.get(owner)
        if owner_record is None or owner_record.get("status") == "left" or is_stale(
                owner_record, config["stale_minutes"]):
            tid = task["id"]
            items.append({"key": "stale_owner:%s:%s" % (tid, owner), "kind": "stale_owner",
                          "task": tid, "text": "Task %s has stale or left owner %s." % (tid, owner)})

    for task in tasks:
        if task.get("status") != "blocked":
            continue
        qid = None
        for entry in reversed(task.get("log", [])):
            if entry.get("event") == "blocked":
                match = re.match(r"^(Q\d{3,}):", entry.get("note", ""))
                if match:
                    qid = match.group(1)
                break
        if qid and questions_by_id.get(qid, {}).get("status") == "resolved":
            tid = task["id"]
            items.append({"key": "answered:%s" % tid, "kind": "answered", "task": tid,
                          "text": "The question blocking %s has been answered." % tid})

    threshold = int(config.get("usage_warn_percent", 80))
    for agent in sorted(agents.values(), key=lambda record: record.get("id", "")):
        usage = agent.get("usage") or {}
        percent = usage.get("percent")
        if agent.get("status") == "active" and percent is not None and percent >= threshold:
            aid = agent["id"]
            items.append({"key": "usage_high:%s" % aid, "kind": "usage_high", "task": None,
                          "text": "%s reported usage at %s%%." % (aid, percent)})

    if claimable_tasks(team_dir, tasks) and not any(
            task.get("status") in LIVE_STATUSES for task in tasks):
        items.append({"key": "idle", "kind": "idle", "task": None,
                      "text": "Claimable work is waiting and no task is active."})
    if tasks and all(task.get("status") == "done" for task in tasks):
        items.append({"key": "complete", "kind": "complete", "task": None,
                      "text": "All tasks are done."})
    return items


def add_log(task: dict, agent: str, event: str, note: str = "") -> None:
    task["log"].append({"at": now_iso(), "agent": agent, "event": event, "note": note})


def normalize_path(team_dir: Path, path: str) -> str:
    """Spell a registered path one way: relative to the project folder (the parent of team/), with
    / separators, when it is inside the project ("." for the project itself); absolute otherwise.
    So `src/app.py`, `./src/../src/app.py` and `/abs/project/src/app.py` are the same path."""
    raw = path.strip().replace("\\", "/")
    if any(char in raw for char in "*?[]"):
        raise TeamError('wildcards are not supported in reserved paths (%r); register a specific '
                        'file or directory instead' % raw)
    if not raw:
        raise TeamError("a path is empty")
    return normalize_stored_path(team_dir, raw)


def normalize_stored_path(team_dir: Path, path: str) -> str:
    """Canonicalize an existing reservation without rejecting legacy glob registrations."""
    root = Path(team_dir).resolve().parent
    raw = str(path).strip().replace("\\", "/")
    full = Path(raw) if os.path.isabs(raw) else root / raw
    try:
        full = full.resolve(strict=False)
    except (OSError, RuntimeError) as exc:
        raise TeamError("cannot resolve path %r: %s" % (raw, exc))
    try:
        spelled = full.relative_to(root).as_posix()
    except ValueError:
        spelled = full.as_posix()
    keep_slash = raw.endswith("/") and not spelled.endswith("/") and spelled != "."
    return spelled + "/" if keep_slash else spelled


def _norm_path(path: str) -> str:
    path = path.strip().replace("\\", "/")
    while path.startswith("./"):
        path = path[2:]
    path = path.rstrip("/")
    return "" if path == "." else path  # "" means the whole project


def _reservation_tree(path: str) -> str:
    """Older boards may contain globs. Reserve the directory before the first wildcard."""
    path = _norm_path(path)
    if sys.platform == "darwin" or os.name == "nt":
        path = path.casefold()
    parts = path.split("/")
    for index, part in enumerate(parts):
        if any(char in part for char in "*?[]"):
            return "/".join(parts[:index])
    return path


def paths_overlap(a: str, b: str) -> bool:
    """Equal or nested reservations overlap. An empty tree denotes the whole project."""
    a, b = _reservation_tree(a), _reservation_tree(b)
    return not a or not b or a == b or a.startswith(b + "/") or b.startswith(a + "/")


def find_overlap(team_dir: Path, tasks: list, task: dict, paths: list):
    """Return (path, other_path, other_task) for the first clash with a live task, else None."""
    for other in tasks:
        if other["id"] == task["id"] or other["status"] not in RESERVATION_STATUSES:
            continue
        for mine in paths:
            for theirs in other.get("files", []):
                if paths_overlap(normalize_stored_path(team_dir, mine),
                                 normalize_stored_path(team_dir, theirs)):
                    return mine, theirs, other
    return None


def unmet_dependency(tasks_by_id: dict, task: dict):
    """Return the first dependency that is not done (dict, or the bare ID if missing), else None."""
    for dep_id in task.get("depends_on", []):
        dep = tasks_by_id.get(dep_id)
        if dep is None or dep["status"] != "done":
            return dep if dep is not None else dep_id
    return None


def require_owner(task: dict, agent: str) -> None:
    """Refuse unless agent owns task; name the owner and any `reclaimed from` log entry."""
    if task.get("owner") == agent:
        return
    reason = "%s is owned by %s (%s), not by %s" % (
        task["id"], task.get("owner") or "nobody", task["status"], agent)
    for entry in reversed(task.get("log", [])):
        if entry.get("event", "").startswith("reclaimed from"):
            reason += "; %s by %s at %s" % (entry["event"], entry["agent"], entry["at"])
            break
    if task["status"] == "available":
        raise refuse(reason, "claim %s --agent %s" % (task["id"], agent))
    raise refuse(reason, "next --agent %s" % agent)


