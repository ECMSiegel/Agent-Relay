def project_name(team_dir: Path) -> str:
    plan = Path(team_dir) / "PLAN.md"
    if plan.is_file():
        for line in plan.read_text(encoding="utf-8").splitlines():
            match = re.match(r"^#+\s+(.*\S)", line)
            if match:
                return match.group(1)
    return Path(team_dir).resolve().parent.name


def _cell(value) -> str:
    return str(value if value not in (None, "") else "-").replace("|", "\\|").replace("\n", " ")


def _one_line(value) -> str:
    """Fold newlines and runs of whitespace into single spaces, so a view's bullet stays one line."""
    return " ".join(str(value).split())


def _files_text(task: dict) -> str:
    return ", ".join("`%s`" % f for f in task.get("files", [])) or "none"


def _message_line(m: dict) -> str:
    task = " (%s)" % m["task"] if m.get("task") else ""
    return "- #%s %s %s -> %s [%s]%s: %s" % (
        m.get("id"), m.get("at"), m.get("from"), m.get("to"), m.get("kind"), task,
        _one_line(m.get("text")))


def load_questions(team_dir: Path) -> list:
    folder = Path(team_dir) / "questions"
    if not folder.is_dir():
        return []
    return [read_json(p) for p in sorted(folder.glob("Q*.json"))]


def render_board(team_dir: Path, config: dict, show_left: bool = False) -> str:
    agents = load_agents(team_dir)
    tasks = load_tasks(team_dir)
    messages = read_jsonl(Path(team_dir) / "messages.jsonl")
    questions = load_questions(team_dir)
    out = [VIEW_HEADER, "# Team board: %s" % project_name(team_dir), "",
           "Updated: %s" % now_iso(), "", "## Agents", ""]
    rows = agents if show_left else [a for a in agents if a.get("status") != "left"]
    hidden = len(agents) - len(rows)
    if agents:
        out.append("| ID | Label | Status | Current task | Last seen | Stale |")
        out.append("|---|---|---|---|---|---|")
        for a in rows:
            stale = "STALE" if is_stale(a, config["stale_minutes"]) else ""
            out.append("| %s | %s | %s | %s | %s | %s |" % (
                _cell(a["id"]), _cell(a.get("label")), _cell(a.get("status")),
                _cell(a.get("current_task")), _cell(a.get("last_seen")), _cell(stale)))
        if hidden:
            out += ["", "%d left agent%s hidden (status --all lists them)"
                    % (hidden, "" if hidden == 1 else "s")]
    else:
        out.append("No agents have joined yet.")
    gone = {a["id"]: "LEFT" if a.get("status") == "left" else "STALE" for a in agents
            if a.get("status") == "left" or is_stale(a, config["stale_minutes"])}
    out += ["", "## Tasks", ""]
    for status in STATUSES:
        group = [t for t in tasks if t["status"] == status]
        out.append("### %s (%d)" % (status, len(group)))
        for t in group:
            flags = ""
            if status in LIVE_STATUSES and t.get("owner") in gone:
                flags = " [OWNER %s]" % gone[t["owner"]]
            out.append("- %s [p%s] %s; owner: %s; files: %s%s" % (
                t["id"], t.get("priority"), _one_line(t["title"]), t.get("owner") or "-",
                _files_text(t),
                flags))
        out.append("")
    open_count = sum(1 for q in questions if q.get("status") == "open")
    out += ["## Open questions: %d" % open_count, "", "## Last 10 messages", ""]
    out += [_message_line(m) for m in messages[-10:]] or ["No messages yet."]
    return "\n".join(out) + "\n"


