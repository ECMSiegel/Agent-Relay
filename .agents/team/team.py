class TeamError(Exception):
    """A command failed. code: 1 usage/validation, 2 refused by a rule, 3 lock busy.

    hint is the next command to suggest (printed as `Run: team.py <hint>`).
    """

    def __init__(self, message: str, code: int = 1, hint: str | None = None):
        super().__init__(message)
        self.code = code
        self.hint = hint


def refuse(message: str, hint: str) -> TeamError:
    """A refusal by a team rule (exit 2). hint, the next command to run, is required."""
    if not hint:
        raise ValueError("refuse() needs a hint")
    return TeamError(message, code=2, hint=hint)


