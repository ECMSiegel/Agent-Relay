def _clear_current_task(team_dir: Path, agent_id: str | None, task_id: str) -> None:
    """Forget task_id as agent_id's current task (no heartbeat). `user` and unknown IDs are skipped."""
    if not agent_id or agent_id == USER or not AGENT_ID_RE.match(agent_id):
        return
