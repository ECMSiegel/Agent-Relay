def cmd_review(team_dir: Path, args, agent: str) -> int:
    touch_agent(team_dir, agent)
    task = _existing_task(team_dir, args.task)
    if task["status"] != "review":
        raise refuse("%s is %s, not in review" % (task["id"], task["status"]),
                     "next --agent %s" % agent)
    if task.get("owner") == agent:
        raise refuse("%s is your own task (you are its owner); another agent or the user must "
                     "review it" % task["id"], "next --agent %s" % agent)
    if args.reject and not (args.note or "").strip():
        raise TeamError("--reject needs --note (the note becomes the task's handoff)")
    owner = task.get("owner")
    stamp = now_iso()
    verdict = "approved" if args.approve else "rejected"
    task["review"] = {"by": agent, "at": stamp, "verdict": verdict, "note": args.note or ""}
    task["updated_at"] = stamp
    task["owner"] = None
    add_log(task, agent, verdict, args.note or "")
    if args.approve:
        task["status"] = "done"
        _wt_on_finish(team_dir, task)
    else:
        task["status"] = "available"
        task["claimed_at"] = None
        task["handoff"] = {"by": agent, "at": stamp, "text": args.note}
        _notify_agent(team_dir, agent, owner,
                      "%s was rejected by %s and is available again: %s"
                      % (task["id"], agent, args.note), task["id"])
    save_task(team_dir, task)
    _clear_current_task(team_dir, owner, task["id"])
    print("%s %s by %s." % (task["id"], verdict, agent))
    return 0


