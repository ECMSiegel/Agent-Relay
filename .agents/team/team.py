def cmd_claim(team_dir: Path, args, agent: str) -> int:
    me = touch_agent(team_dir, agent)
    hint = "next --agent %s" % agent
    tasks = load_tasks(team_dir)
    tasks_by_id = {t["id"]: t for t in tasks}
    task = tasks_by_id.get(args.task)
    if task is None:
        raise TeamError("task %s does not exist" % args.task)
    if task["status"] != "available":
        owner = " by %s" % task["owner"] if task.get("owner") else ""
        raise refuse("%s is %s%s, not available" % (task["id"], task["status"], owner),
                     _state_hint(task, agent) if task.get("owner") == agent else hint)
    dep = unmet_dependency(tasks_by_id, task)
    if isinstance(dep, dict):
        owner = ", owner %s" % dep["owner"] if dep.get("owner") else ""
        raise refuse("%s depends on %s, which is %s%s" % (task["id"], dep["id"], dep["status"],
                                                           owner), hint)
    if dep is not None:
        raise refuse("%s depends on %s, which does not exist" % (task["id"], dep), hint)
    clash = find_overlap(team_dir, tasks, task, task.get("files", []))
    if clash:
        mine, theirs, other = clash
        raise refuse('%s path "%s" overlaps "%s" of %s (owner %s, %s)' % (
            task["id"], mine, theirs, other["id"], other.get("owner"), other["status"]), hint)
    # CLAIM-CHECK-THEN-WRITE
    worktree_lines = _wt_on_take(team_dir, task)
    stamp = now_iso()
    task["status"] = "claimed"
    task["owner"] = agent
    task["claimed_at"] = stamp
    task["updated_at"] = stamp
    add_log(task, agent, "claimed")
    save_task(team_dir, task)
    me["current_task"] = task["id"]
    save_agent(team_dir, me)
    print("Claimed %s. Next: team.py start %s --agent %s" % (task["id"], task["id"], agent))
    for line in worktree_lines:
        print(line)
    print(format_task(task, tasks_by_id))
    return 0


