def _copy_file(src: Path, dst: Path) -> None:
    write_text_atomic(dst, src.read_text(encoding="utf-8"))


def _check_launcher(team_dir: Path) -> None:
    """Run the new launcher once, as an agent would (`python3 team/team.py --help`)."""
    result = subprocess.run([sys.executable, str(Path("team") / "team.py"), "--help"],
                            cwd=str(team_dir.parent), stdout=subprocess.DEVNULL,
                            stderr=subprocess.PIPE, universal_newlines=True)
    if result.returncode != 0:
        raise TeamError('team/team.py cannot reach the tool (%s); run instead: python3 "%s" init '
                        "--standalone" % (result.stderr.strip() or "exit %d" % result.returncode,
                                          TOOL_PATH))


def cmd_init(args) -> int:
    team_dir = Path.cwd() / "team"
    for sub in ("", "tasks", "agents", "questions"):
        (team_dir / sub).mkdir(parents=True, exist_ok=True)
    for name in ("messages.jsonl", "decisions.jsonl", "discoveries.jsonl"):
        if not (team_dir / name).exists():
            write_text_atomic(team_dir / name, "")
    for src_name, dst_name in (("config.default.json", "config.json"),
                               ("PLAN.template.md", "PLAN.md")):
        dst = team_dir / dst_name
        if dst.exists():
            continue
        src = TOOL_DIR / src_name
        if not src.is_file():
            raise TeamError("%s not found beside the tool (%s); cannot create team/%s"
                            % (src_name, TOOL_DIR, dst_name))
        _copy_file(src, dst)
    protocol_src, protocol_dst = TOOL_DIR / "PROTOCOL.md", team_dir / "PROTOCOL.md"
    if protocol_src.is_file() and protocol_src.resolve() != protocol_dst.resolve():
        _copy_file(protocol_src, protocol_dst)
    elif not protocol_dst.is_file():
        raise TeamError("PROTOCOL.md not found beside the tool (%s)" % TOOL_DIR)
    tool_dst = team_dir / "team.py"
    if tool_dst.exists() and tool_dst.resolve() == TOOL_PATH:
        print("team/team.py is the running tool; left unchanged.")
    elif args.standalone:
        _copy_file(TOOL_PATH, tool_dst)
    else:
        kit_root = TOOL_DIR.parent.parent
        nested = TOOL_DIR.parent.name == ".agents" and kit_root in team_dir.resolve().parents
        location = os.path.relpath(TOOL_PATH, team_dir) if nested else str(TOOL_PATH)
        write_text_atomic(tool_dst, SHIM_TEXT % location)
    acquire_lock(team_dir, "init")
    try:
        render_views(team_dir)
    finally:
        release_lock(team_dir)
    if not args.standalone and tool_dst.resolve() != TOOL_PATH:
        _check_launcher(team_dir)
    print("Team folder ready: %s" % team_dir)
    print('Next: fill in team/PLAN.md; agents run: python3 team/team.py join --label "<tool name>"')
    return 0


def cmd_join(team_dir: Path, args, agent: str | None) -> int:
    # Compared without case: on a case-insensitive filesystem A1.json would overwrite a1.json.
    existing = {p.stem.lower(): p.stem for p in (team_dir / "agents").glob("*.json")}
    if agent:
        if agent.lower() in RESERVED_IDS or not AGENT_ID_RE.match(agent):
            raise TeamError("invalid agent ID %r: use letters, digits, '.', '_' or '-' "
                            "(not 'user', 'all' or 'coordinator')" % agent)
        clash = existing.get(agent.lower())
        if clash is not None and clash != agent:
            raise refuse("agent ID %s clashes with existing agent %s (IDs ignore case)"
                         % (agent, clash),
                         'join --label "<your tool name>" (without --agent, for a new ID)')
        if clash is not None:
            record = read_json(agent_path(team_dir, agent))
            if record.get("status") != "left":
                raise refuse("agent ID %s is already active" % agent,
                             'join --label "<your tool name>" (without --agent, for a new ID)')
            record["status"] = "active"
            record["last_seen"] = now_iso()
            if args.label is not None:
                record["label"] = args.label
            if args.role is not None:
                record["role"] = args.role
            record.setdefault("role", None)
            record.setdefault("busy_until", None)
            save_agent(team_dir, record)
            print("You are %s. Pass --agent %s on every command." % (agent, agent))
            return 0
        new_id = agent
    else:
        new_id = "agent-%s" % uuid.uuid4().hex[:4]
        while new_id in existing:
            new_id = "agent-%s" % uuid.uuid4().hex[:4]
    stamp = now_iso()
    # A new agent starts after the existing history, so its first inbox is not the whole log.
    messages = read_jsonl(team_dir / "messages.jsonl")
    cursor = max([m.get("id", 0) for m in messages] or [0])
    save_agent(team_dir, {"id": new_id, "label": args.label or "", "joined_at": stamp,
                          "last_seen": stamp, "status": "active", "current_task": None,
                          "inbox_cursor": cursor, "role": args.role, "busy_until": None})
    print("You are %s. Pass --agent %s on every command." % (new_id, new_id))
    return 0


