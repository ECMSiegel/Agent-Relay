LOG_NOTE_LIMIT = 240


def _trim_log_note(entry: dict) -> str:
    """A long note, cut for `show`; rejection, review and handoff notes are what the next
    owner works from, so they are never cut."""
    note, event = entry["note"], entry.get("event") or ""
    if len(note) <= LOG_NOTE_LIMIT or event in ("rejected", "review requested") \
            or event.startswith("handoff"):
        return note
    return note[:LOG_NOTE_LIMIT] + " [... show --full]"


def format_task(task: dict, tasks_by_id: dict | None = None, trim_log: bool = False) -> str:
    tasks_by_id = tasks_by_id or {}
    out = ["%s: %s" % (task["id"], task["title"]),
           "Status: %s | Owner: %s | Priority: %s | Review required: %s" % (
               task["status"], task.get("owner") or "-", task.get("priority"),
               "yes" if task.get("review_required") else "no")]
    deps = []
    for dep_id in task.get("depends_on", []):
        dep = tasks_by_id.get(dep_id)
        deps.append("%s (%s)" % (dep_id, dep["status"] if dep else "missing"))
    out.append("Depends on: %s" % (", ".join(deps) or "none"))
    out.append("Registered paths:")
    out += ["  - %s" % f for f in task.get("files", [])] or ["  (none)"]
    out.append("Description:")
    out += ["  %s" % line for line in (task.get("description") or "").splitlines()] or ["  (none)"]
    handoff = task.get("handoff")
    if handoff:
        out.append("HANDOFF NOTE from %s at %s (read it fully before working):" % (
            handoff.get("by"), handoff.get("at")))
        out += ["  %s" % line for line in (handoff.get("text") or "").splitlines()]
    review = task.get("review")
    if review:
        out.append("Review by %s at %s: %s. %s" % (
            review.get("by"), review.get("at"), review.get("verdict"), review.get("note") or ""))
    out.append("Log:")
    for entry in task.get("log", []):
        note = ": %s" % (_trim_log_note(entry) if trim_log else entry["note"]) \
            if entry.get("note") else ""
        out.append("  %s %s %s%s" % (entry["at"], entry["agent"], entry["event"], note))
    return "\n".join(out)


