def acquire_lock(team_dir: Path, agent: str) -> None:  # LOCK-ACQUIRE
    team_dir = Path(team_dir)
    config = load_config(team_dir)
    lock = team_dir / ".lock"
    stale_after = float(config["lock_stale_seconds"])
    deadline = time.monotonic() + float(config["lock_timeout_seconds"])
    while True:
        try:
            fd = os.open(str(lock), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        except FileExistsError:
            pass
        else:
            text = "%s %d %s" % (agent, os.getpid(), now_iso())
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(text)
            _HELD_LOCKS[str(lock)] = text
            return
        try:
            seen = os.stat(str(lock))
        except FileNotFoundError:
            continue  # released between our create and stat; retry at once
        stale = time.time() - seen.st_mtime > stale_after
        if stale and _break_stale_lock(lock, seen):
            continue
        if time.monotonic() >= deadline:
            raise TeamError("team lock busy", code=3)
        time.sleep(random.uniform(0.010, 0.050))


def _break_stale_lock(lock: Path, seen: os.stat_result) -> bool:
    """Remove the stale lock `seen`; return True to retry at once, False to wait.

    Breakers take turns through a second exclusive file (`.lock.break`) and re-check, while
    holding it, that the lock is still the very file judged stale. Without that, a process that
    judged the old lock stale could rename away a fresh lock another process had just taken, and
    two processes would hold the lock at once. The stale file is moved to a unique name and then
    deleted, never deleted under the shared name.
    """
    breaker = Path("%s.break" % lock)
    try:
        fd = os.open(str(breaker), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        with contextlib.suppress(FileNotFoundError):
            guard = os.stat(str(breaker))
            if time.time() - guard.st_mtime > BREAK_GUARD_STALE_SECONDS:
                _remove_if_unchanged(breaker, guard, lock)  # a breaker died mid-break
        return False
    try:
        mine = os.fstat(fd)
    finally:
        os.close(fd)
    try:
        try:
            now = os.stat(str(lock))
        except FileNotFoundError:
            return True
        if (now.st_ino, now.st_mtime_ns) != (seen.st_ino, seen.st_mtime_ns):
            return False  # the lock changed hands since we looked; it is not stale
        broken = "%s.broken.%s" % (lock, uuid.uuid4().hex)
        try:
            os.rename(str(lock), broken)
        except FileNotFoundError:
            return True
        with contextlib.suppress(FileNotFoundError):
            os.unlink(broken)
        return True
    finally:
        _remove_if_unchanged(breaker, mine, lock)


def _remove_if_unchanged(path: Path, seen: os.stat_result, lock: Path) -> None:
    """Delete path only if it is still the very file `seen` (same inode and mtime). It is moved to
    a unique name first, so a file another process has just created under the shared name is
    never deleted."""
    try:
        now = os.stat(str(path))
    except FileNotFoundError:
        return
    if (now.st_ino, now.st_mtime_ns) != (seen.st_ino, seen.st_mtime_ns):
        return
    broken = "%s.broken.%s" % (lock, uuid.uuid4().hex)
    try:
        os.rename(str(path), broken)
    except FileNotFoundError:
        return
    with contextlib.suppress(FileNotFoundError):
        os.unlink(broken)


def release_lock(team_dir: Path) -> None:
    """Remove the lock only if it still holds exactly what this process wrote; a holder that
    hung past the stale age must not delete the lock of whoever broke it and took over."""
    lock = str(Path(team_dir) / ".lock")
    mine = _HELD_LOCKS.pop(lock, None)
    try:
        with open(lock, "r", encoding="utf-8") as handle:
            current = handle.read()
    except FileNotFoundError:
        return
    if mine is not None and current == mine:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(lock)


