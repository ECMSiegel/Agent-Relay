def resolve_team_dir() -> Path:
    env = os.environ.get("TEAM_DIR")
    if env:
        team_dir = Path(env).resolve()
        if not (team_dir / "config.json").is_file():
            raise TeamError("TEAM_DIR %s has no config.json; run init in the project folder"
                            % team_dir)
        return team_dir
    here = Path.cwd().resolve()
    for folder in [here] + list(here.parents):
        if (folder / "team" / "config.json").is_file():
            return folder / "team"
    raise TeamError("no team/ folder found; run init in the project folder")


