    def test_a_stale_guard_replaced_meanwhile_is_kept(self):  # finding 7, ruling 5
        lock, guard = self.team / ".lock", self.team / ".lock.break"
        lock.write_text("crashed 1 then")
        guard.write_text("")
        past = time.time() - 60
        os.utime(str(lock), (past, past))
        os.utime(str(guard), (past, past))
        real_stat, swapped = os.stat, []

        def stat(path, *args, **kwargs):
            result = real_stat(path, *args, **kwargs)
            if str(path) == str(guard) and not swapped:  # right after the guard is judged stale,
                swapped.append(True)                     # another breaker replaces it
                os.rename(str(guard), str(guard) + ".old")
                guard.write_text("live")
            return result

        seen = real_stat(str(lock))
        with mock.patch.object(self.tool.os, "stat", stat):
            self.assertFalse(self.tool._break_stale_lock(lock, seen))
        self.assertTrue(guard.is_file(), "the live guard of another breaker was deleted")
        self.assertEqual(guard.read_text(), "live")

