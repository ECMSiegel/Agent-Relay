    def test_lock_busy_exit_3(self):
        self.join("a1")
        self.ok("add", "--agent", "a1", "--title", "t", "--desc", "d")
        self.set_config(lock_timeout_seconds=1)
        (self.team / ".lock").write_text("someone 1 now")
