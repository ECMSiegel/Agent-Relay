class TeamTestCase(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.mkdtemp(prefix="team-test-")
        self.addCleanup(shutil.rmtree, tmp, True)
        self.workspace, self.project = helpers.make_workspace(Path(tmp))
        self.tool_path = self.workspace / ".agents" / "team" / "team.py"
        self.tool = helpers.load_tool(self.tool_path)
        self.team = self.project / "team"
        saved = {k: os.environ.get(k) for k in ("TEAM_DIR", "TEAM_AGENT")}
        self.addCleanup(self._restore_env, saved)
        for key in saved:
            os.environ.pop(key, None)
        code, _, err = self.in_dir(self.project, "init")
        self.assertEqual(code, 0, err)
        os.environ["TEAM_DIR"] = str(self.team)

    @staticmethod
    def _restore_env(saved):
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value

    # -- helpers --
    def main(self, *argv):
        return helpers.run(self.tool, *argv)

    def in_dir(self, folder, *argv):
        old = os.getcwd()
        os.chdir(str(folder))
        try:
            return helpers.run(self.tool, *argv)
        finally:
            os.chdir(old)

    def ok(self, *argv):
        code, out, err = self.main(*argv)
        self.assertEqual(code, 0, "%s -> %s %s" % (argv, out, err))
        return out

    def join(self, *ids):
        for agent in ids:
            self.ok("join", "--agent", agent)

    def task(self, task_id):
        return json.loads((self.team / "tasks" / ("%s.json" % task_id)).read_text())

    def agent(self, agent_id):
        return json.loads((self.team / "agents" / ("%s.json" % agent_id)).read_text())

    def edit_json(self, path, **changes):
        data = json.loads(path.read_text())
        data.update(changes)
        path.write_text(json.dumps(data))

    def set_status(self, task_id, status, owner=None):
        self.edit_json(self.team / "tasks" / ("%s.json" % task_id), status=status, owner=owner)

    def set_config(self, **changes):
        self.edit_json(self.team / "config.json", **changes)

    def clean_env(self):
        return {k: v for k, v in os.environ.items() if k not in ("TEAM_DIR", "TEAM_AGENT")}

    def run_shim(self, *argv):
        return subprocess.run([sys.executable, "team/team.py"] + list(argv), cwd=str(self.project),
                              env=self.clean_env(), capture_output=True, text=True, timeout=60)

    def spawn_all(self, target, arglists):
        ctx = multiprocessing.get_context("spawn")
        barrier = ctx.Barrier(len(arglists))
        queue = ctx.Queue()
        procs = [ctx.Process(target=target, args=tuple(a) + (barrier, queue)) for a in arglists]
        for p in procs:
            p.start()
        results = [queue.get(timeout=120) for _ in procs]
        for p in procs:
            p.join(timeout=30)
            self.assertFalse(p.is_alive(), "worker process hung")
        return results


class InitTests(TeamTestCase):
    def test_init_creates_layout_and_views(self):
        for sub in ("tasks", "agents", "questions"):
            self.assertTrue((self.team / sub).is_dir(), sub)
        for name in ("messages.jsonl", "decisions.jsonl", "discoveries.jsonl"):
            self.assertEqual((self.team / name).read_text(), "", name)
        self.assertEqual((self.team / "config.json").read_text(),
                         (self.workspace / ".agents/team/config.default.json").read_text())
        self.assertEqual((self.team / "PLAN.md").read_text(),
                         (self.workspace / ".agents/team/PLAN.template.md").read_text())
        self.assertEqual((self.team / "PROTOCOL.md").read_text(),
                         (self.workspace / ".agents/team/PROTOCOL.md").read_text())
        self.assertIn("runpy.run_path", (self.team / "team.py").read_text())
        self.assertFalse((self.team / ".lock").exists())

    def test_init_idempotent_never_overwrites_plan_or_config(self):
        self.join("a1")
        self.ok("add", "--agent", "a1", "--title", "t", "--desc", "d")
        (self.team / "PLAN.md").write_text("# My plan\n")
        self.set_config(stale_minutes=45)
        config_before = (self.team / "config.json").read_text()
        task_before = (self.team / "tasks" / "T001.json").read_text()
        agent_before = (self.team / "agents" / "a1.json").read_text()
        (self.team / "PROTOCOL.md").write_text("stale copy")
        (self.team / "team.py").write_text("broken shim")
        os.environ.pop("TEAM_DIR")
        code, _, err = self.in_dir(self.project, "init")
        self.assertEqual(code, 0, err)
        self.assertEqual((self.team / "PLAN.md").read_text(), "# My plan\n")
        self.assertEqual((self.team / "config.json").read_text(), config_before)
        self.assertEqual((self.team / "tasks" / "T001.json").read_text(), task_before)
        self.assertEqual((self.team / "agents" / "a1.json").read_text(), agent_before)
        self.assertEqual((self.team / "PROTOCOL.md").read_text(),
                         (self.workspace / ".agents/team/PROTOCOL.md").read_text())
        self.assertIn("runpy.run_path", (self.team / "team.py").read_text())
        self.assertIn("# Team board: My plan", (self.team / "BOARD.md").read_text())

    def test_init_standalone_works_without_workspace_tool(self):
        os.environ.pop("TEAM_DIR")
        code, _, err = self.in_dir(self.project, "init", "--standalone")
        self.assertEqual(code, 0, err)
        tool_bytes = self.tool_path.read_bytes()
        self.assertEqual((self.team / "team.py").read_bytes(), tool_bytes)
        shutil.rmtree(str(self.workspace / ".agents" / "team"))
        result = self.run_shim("join", "--agent", "s1")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("You are s1.", result.stdout)
        result = self.run_shim("add", "--agent", "s1", "--title", "t", "--desc", "d")
        self.assertEqual((result.returncode, result.stdout.strip()), (0, "T001"), result.stderr)
        result = self.run_shim("claim", "T001", "--agent", "s1")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(self.task("T001")["owner"], "s1")
        # re-running init with the standalone copy keeps the copy and the state
        result = self.run_shim("init", "--standalone")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual((self.team / "team.py").read_bytes(), tool_bytes)
        self.assertEqual(self.task("T001")["owner"], "s1")


